    private fun file(path: String, content: String) = GeneratedApplicationFile(path, content.trimIndent().trim() + "\n")

    /** JSON-style string literals are also valid Kotlin and Python here; escape dollar for Kotlin separately. */
    private fun literal(value: String): String = buildString {
        append('"')
        for (character in value) when (character) {
            '"' -> append("\\\"")
            '\\' -> append("\\\\")
            '\n' -> append("\\n")
            '\t' -> append("\\t")
            '$' -> append("\\u0024")
            '\u0085' -> append("\\u0085")
            '\u2028' -> append("\\u2028")
            '\u2029' -> append("\\u2029")
            else -> append(character)
        }
        append('"')
    }

    private fun csharpLiteral(value: String): String = literal(value)
