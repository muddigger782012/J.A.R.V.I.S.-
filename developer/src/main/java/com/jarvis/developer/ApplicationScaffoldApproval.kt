package com.jarvis.developer

import java.io.ByteArrayOutputStream
import java.nio.charset.StandardCharsets
import java.security.MessageDigest
import java.util.Collections
import java.util.zip.CRC32
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream

enum class ApplicationPlatform { ANDROID, BACKEND, WINDOWS }
enum class AndroidApplicationBehavior { COUNTER, CHECKLIST }

data class ApplicationSpecification(
    val title: String,
    val writtenSpec: String,
    val platform: ApplicationPlatform,
    val projectName: String,
    val packageName: String,
    val androidBehavior: AndroidApplicationBehavior = AndroidApplicationBehavior.COUNTER
)

data class GeneratedApplicationFile(val path: String, val content: String)

class ApplicationScaffoldPlan internal constructor(
    val specification: ApplicationSpecification,
    files: List<GeneratedApplicationFile>,
    val fingerprint: String
) {
    val files: List<GeneratedApplicationFile> = Collections.unmodifiableList(files.toList())
    val templateVersion: String get() = ApplicationScaffolds.templateVersion(specification)
}

class ApplicationScaffoldApproval private constructor(internal val fingerprint: String) {
    companion object {
        internal fun confirm(plan: ApplicationScaffoldPlan, exactFingerprint: String, confirmed: Boolean): ApplicationScaffoldApproval {
            ApplicationScaffolds.review(plan)
            require(confirmed) { "Explicit review confirmation is required" }
            require(exactFingerprint == plan.fingerprint) { "Approval must name the exact reviewed fingerprint" }
            return ApplicationScaffoldApproval(plan.fingerprint)
        }
    }
}

/** Fixed, reviewable starter templates. This engine has no file, network, process or signing API. */
object ApplicationScaffolds {
    const val MAX_FILES = 32
    const val MAX_BYTES = 512 * 1024
    const val MAX_SPEC_CHARACTERS = 4000
    const val TEMPLATE_VERSION = "jarvis-starter-v1"
    const val CHECKLIST_TEMPLATE_VERSION = "jarvis-checklist-v1"
    internal fun templateVersion(spec: ApplicationSpecification) =
        if (spec.platform == ApplicationPlatform.ANDROID && spec.androidBehavior == AndroidApplicationBehavior.CHECKLIST)
            CHECKLIST_TEMPLATE_VERSION else TEMPLATE_VERSION
    private val packagePattern = Regex("[a-z][a-z0-9]{0,29}(?:\\.[a-z][a-z0-9]{0,29}){1,5}")
    private val reserved = setOf("class", "object", "fun", "val", "var", "when", "in", "is", "as",
        "if", "else", "for", "while", "do", "try", "catch", "finally", "throw", "return", "break",
        "continue", "this", "super", "package", "import", "interface", "enum", "null", "true", "false",
        "new", "public", "private", "protected", "static", "void", "int", "long", "float", "double",
        "boolean", "byte", "short", "char", "switch", "case", "default", "extends", "implements",
        "instanceof", "synchronized", "volatile", "transient", "native", "assert", "const", "goto", "typealias", "typeof")
    private val secret = Regex("(?i)(?:\\b(?:gh[pousr]_[a-z0-9_]{12,}|github_pat_[a-z0-9_]{12,}|sk-[a-z0-9_-]{12,}|AIza[a-z0-9_-]{20,})\\b|-----BEGIN [A-Z ]*PRIVATE KEY-----|\\b(?:api[_ -]?key|access[_ -]?token|password|secret|authorization)\\s*[:=]\\s*[^\\s])")

    fun plan(specification: ApplicationSpecification): ApplicationScaffoldPlan {
        validateSpecification(specification)
        val files = generatedFiles(specification).sortedBy { it.path }
        validateFiles(files)
        return ApplicationScaffoldPlan(specification, files, fingerprint(specification, files))
    }

    /** Includes every generated byte as text; review is never an abbreviated file list. */
    fun review(plan: ApplicationScaffoldPlan): String {
        validatePlan(plan)
        return buildString {
            append("Fixed starter template: ").append(plan.templateVersion).append('\n')
            append("Platform: ").append(plan.specification.platform).append('\n')
            append("Project: ").append(plan.specification.projectName).append('\n')
            append("Package: ").append(plan.specification.packageName).append('\n')
            append("Fingerprint SHA-256: ").append(plan.fingerprint).append('\n')
            append("Approval permits ZIP export only. No build, install, publication, repository write or provider request.\n")
            if (plan.specification.androidBehavior == AndroidApplicationBehavior.CHECKLIST)
                append("Implemented behavior: offline task list; add, complete and confirm removal of completed tasks; private local persistence and confirmed reset. Other written requirements are not implemented.\n")
            else append("The written specification is displayed by a fixed starter; arbitrary requested features are not implemented.\n")
            for (file in plan.files) {
                append("\n=== ").append(file.path).append(" (")
                    .append(file.content.toByteArray(StandardCharsets.UTF_8).size).append(" UTF-8 bytes) ===\n")
                append(file.content)
                append("=== END ").append(file.path).append(" ===\n")
            }
        }.also { require(it.toByteArray(StandardCharsets.UTF_8).size <= MAX_BYTES + 32768) { "Review exceeds its budget" } }
    }

    fun approve(plan: ApplicationScaffoldPlan, exactFingerprint: String, confirmed: Boolean): ApplicationScaffoldApproval {
        return ApplicationScaffoldApproval.confirm(plan, exactFingerprint, confirmed)
    }

    fun exportZip(plan: ApplicationScaffoldPlan, approval: ApplicationScaffoldApproval): ByteArray {
        validatePlan(plan)
        require(approval.fingerprint == plan.fingerprint) { "The approval belongs to a different plan" }
        return ByteArrayOutputStream().use { bytes ->
            ZipOutputStream(bytes, StandardCharsets.UTF_8).use { zip ->
                for (file in plan.files) {
                    val content = file.content.toByteArray(StandardCharsets.UTF_8)
                    val entry = ZipEntry(file.path)
                    // Pre-DOS epoch produces a fixed DOS date and UTC extended timestamp on Android/JVM.
                    entry.time = 0L
                    // Stored text avoids platform zlib differences in an otherwise identical export.
                    entry.method = ZipEntry.STORED
                    entry.size = content.size.toLong()
                    entry.compressedSize = content.size.toLong()
                    entry.crc = CRC32().apply { update(content) }.value
                    zip.putNextEntry(entry)
                    zip.write(content)
                    zip.closeEntry()
                }
            }
            bytes.toByteArray().also { require(it.size <= MAX_BYTES + 32768) { "ZIP exceeds its budget" } }
        }
    }

    private fun validatePlan(plan: ApplicationScaffoldPlan) {
        validateSpecification(plan.specification)
        validateFiles(plan.files)
        val expected = generatedFiles(plan.specification).sortedBy { it.path }
        require(plan.files == expected && plan.fingerprint == fingerprint(plan.specification, expected)) {
            "The plan differs from its immutable fixed-template review"
        }
    }

    private fun validateSpecification(spec: ApplicationSpecification) {
        require(spec.platform == ApplicationPlatform.ANDROID || spec.androidBehavior == AndroidApplicationBehavior.COUNTER) {
            "Task-list behavior requires the Android platform"
        }
        require(spec.title.isNotBlank() && spec.title.length <= 80 && spec.title == spec.title.trim() &&
            spec.title.none { it in "\n\t\u0085\u2028\u2029" }) { "Title must contain 1–80 visible characters" }
        require(spec.writtenSpec.isNotBlank() && spec.writtenSpec.length <= MAX_SPEC_CHARACTERS) {
            "Written specification must contain 1–4000 characters"
        }
        require(Regex("[A-Z][A-Za-z0-9]{2,39}").matches(spec.projectName)) {
            "Project name must be 3–40 letters/digits starting with an uppercase letter"
        }
        require(packagePattern.matches(spec.packageName) && spec.packageName.split('.').none { it in reserved }) {
            "Package must contain 2–6 lowercase non-reserved name segments"
        }
        require(!spec.packageName.startsWith("com.jarvis") && !spec.packageName.startsWith("com.assistant") &&
            spec.packageName.split('.').none { it == "jarvis" }) { "Use an independent application package" }
        for (value in listOf(spec.title, spec.writtenSpec, spec.projectName, spec.packageName)) {
            require(StandardCharsets.UTF_8.newEncoder().canEncode(value) && value.none {
                (it.code < 32 && it != '\n' && it != '\t') || it.code == 127 ||
                    it.code in 0x202a..0x202e || it.code in 0x2066..0x2069
            }) { "Control or invalid text is not supported" }
            require(!secret.containsMatchIn(value)) { "Do not include credentials or private keys" }
            require('`' !in value && "$(" !in value && "\u0000" !in value) {
                "Shell substitutions are not accepted in a written specification"
            }
        }
    }

    private fun validateFiles(files: List<GeneratedApplicationFile>) {
        require(files.size in 1..MAX_FILES && files.map { it.path }.distinct().size == files.size) { "Invalid file count" }
        require(files == files.sortedBy { it.path }) { "Files must have stable path order" }
        var bytes = 0L
        for (file in files) {
            require(file.path.length <= 200 && file.path.split('/').all {
                it.isNotEmpty() && it != "." && it != ".." && Regex("[A-Za-z0-9_.-]+").matches(it)
            } && !file.path.startsWith('/') && '\\' !in file.path && ':' !in file.path) { "Unsafe generated path" }
            require(file.content.endsWith('\n') && '\u0000' !in file.content) { "Only newline-terminated text files are allowed" }
            bytes += file.content.toByteArray(StandardCharsets.UTF_8).size
        }
        require(bytes <= MAX_BYTES) { "Generated files exceed their byte budget" }
    }

    private fun fingerprint(spec: ApplicationSpecification, files: List<GeneratedApplicationFile>): String {
        val digest = MessageDigest.getInstance("SHA-256")
        fun part(value: String) {
            val bytes = value.toByteArray(StandardCharsets.UTF_8)
            digest.update(bytes.size.toString().toByteArray(StandardCharsets.US_ASCII))
            digest.update(':'.code.toByte())
            digest.update(bytes)
        }
        listOf(templateVersion(spec), spec.platform.name, spec.title, spec.writtenSpec, spec.projectName, spec.packageName).forEach(::part)
        files.forEach { part(it.path); part(it.content) }
        return digest.digest().joinToString("") { "%02x".format(it) }
    }

    private fun generatedFiles(spec: ApplicationSpecification): List<GeneratedApplicationFile> {
        val files = when (spec.platform) {
            ApplicationPlatform.ANDROID -> android(spec)
            ApplicationPlatform.BACKEND -> backend(spec)
            ApplicationPlatform.WINDOWS -> windows(spec)
        }
        if (spec.platform == ApplicationPlatform.ANDROID && spec.androidBehavior == AndroidApplicationBehavior.CHECKLIST) return files
        return files + GeneratedApplicationFile("README.md", """
            # ${spec.projectName} — generated starter

            This independent project uses a fixed, bounded starter template. It displays the
            supplied title and written specification; it does not implement arbitrary features
            described in that specification. Review every generated file before using it.

            No provider, credential, repository editor, shell runner, installer, signing key,
            update channel or publication integration is included. The application has runtime
            behavior only. ZIP approval does not approve building, installing or publishing it.

            Android: use Gradle 8.7 with Java 17 and Android SDK 34; run
            gradle :app:testDebugUnitTest :app:assembleDebug. No wrapper is bundled. Android
            downloads its declared public build/test dependencies when built; it needs no key.
            Backend: Python 3, python3 -m unittest discover -v; python3 server.py listens
            only on 127.0.0.1:8080. Windows: .NET 8 SDK on Windows, dotnet build
            app/StarterApp.csproj -c Release; dotnet run --project smoke/StarterSmoke.csproj
            -c Release. Use only the command for this archive's platform. Windows smoke
            checks construct and interact with a form; they do not establish visual fidelity.
            No release signing or installer is generated. Android debug assembly is a test APK.
        """.trimIndent() + "\n")
    }

