    private fun backend(spec: ApplicationSpecification): List<GeneratedApplicationFile> = listOf(
        file("server.py", """
            # Independent standard-library starter; loopback HTTP only.
            import json
            from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

            TITLE = ${literal(spec.title)}
            SPECIFICATION = ${literal(spec.writtenSpec)}
            PACKAGE = ${literal(spec.packageName)}

            class Handler(BaseHTTPRequestHandler):
                def do_GET(self):
                    if self.path == "/health":
                        status, data = 200, {"status": "ok"}
                    elif self.path == "/api/info":
                        status, data = 200, {"title": TITLE, "specification": SPECIFICATION, "package": PACKAGE}
                    else:
                        status, data = 404, {"error": "not_found"}
                    body = json.dumps(data, ensure_ascii=False).encode("utf-8")
                    self.send_response(status)
                    self.send_header("Content-Type", "application/json; charset=utf-8")
                    self.send_header("Content-Length", str(len(body)))
                    self.end_headers()
                    self.wfile.write(body)

                def log_message(self, format, *args):
                    pass

            def create_server(port=8080):
                return ThreadingHTTPServer(("127.0.0.1", port), Handler)

            if __name__ == "__main__":
                with create_server() as server:
                    try:
                        server.serve_forever()
                    except KeyboardInterrupt:
                        pass
        """),
        file("test_server.py", """
            import json
            import threading
            import unittest
            import urllib.error
            import urllib.request
            import server

            class ServerTest(unittest.TestCase):
                @classmethod
                def setUpClass(cls):
                    cls.server = server.create_server(0)
                    cls.thread = threading.Thread(target=cls.server.serve_forever, daemon=True)
                    cls.thread.start()
                    cls.base = "http://127.0.0.1:" + str(cls.server.server_address[1])

                @classmethod
                def tearDownClass(cls):
                    cls.server.shutdown()
                    cls.server.server_close()
                    cls.thread.join(timeout=5)

                def read(self, path):
                    with urllib.request.urlopen(self.base + path, timeout=5) as response:
                        self.assertEqual("application/json; charset=utf-8", response.headers["Content-Type"])
                        return json.loads(response.read())

                def test_health(self):
                    self.assertEqual({"status": "ok"}, self.read("/health"))

                def test_written_specification_is_returned_as_data(self):
                    self.assertEqual({"title": server.TITLE, "specification": server.SPECIFICATION,
                                      "package": server.PACKAGE}, self.read("/api/info"))

                def test_unknown_route(self):
                    with self.assertRaises(urllib.error.HTTPError) as caught:
                        self.read("/missing")
                    self.assertEqual(404, caught.exception.code)
                    self.assertEqual({"error": "not_found"}, json.loads(caught.exception.read()))

                def test_server_binds_loopback(self):
                    self.assertEqual("127.0.0.1", self.server.server_address[0])

            if __name__ == "__main__":
                unittest.main()
        """)
    )

